#!/usr/bin/env python3
"""
Hardcode a batch of new students into every repo-side place that needs them,
from ONE source file (e.g. jss1_2026_2027.json), so the sides cannot disagree.

  1. supabase/seed/<name>.sql    -- DB seed with the SAME explicit ids
  2. scripts/report-pipeline/students/<id>.json -- empty, undigitized
     skeletons (same shape sync_students_from_supabase.py produces)
  3. (optional) tendercare-portal src/lib/students.ts -- the portal's
     hardcoded directory, via --portal /path/to/tendercare-portal

Idempotent: existing pipeline files and portal rows are skipped, never
overwritten. No network, no Supabase calls.

Usage (from tendercare-teacher/):
    python3 scripts/intake/build_intake.py scripts/intake/jss1_2026_2027.json \
        --seed-name 003_jss1_intake_2026_2027 --portal ../tendercare-portal
    python3 scripts/intake/build_intake.py <file> --dry-run
"""
import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PIPELINE = ROOT / "scripts" / "report-pipeline"


def load_sync_module():
    spec = importlib.util.spec_from_file_location(
        "sync_students", PIPELINE / "sync_students_from_supabase.py"
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def sql_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def write_seed(doc: dict, name: str, dry: bool) -> Path:
    students = doc["students"]
    year = doc["academic_year"]
    atype = doc["admission_type"]
    path = ROOT / "supabase" / "seed" / f"{name}.sql"
    by_class = {}
    for s in students:
        by_class[s["class_id"]] = by_class.get(s["class_id"], 0) + 1
    summary = ", ".join(f"{c}: {n}" for c, n in sorted(by_class.items()))
    lines = [
        f"-- Seed data: {year} {atype} -- {len(students)} students ({summary}).",
        "--",
        "-- GENERATED by scripts/intake/build_intake.py from the JSON source next to",
        "-- it -- edit that file and re-run, not this one. The same ids are hardcoded",
        "-- into the report pipeline and the portal directory, so the sides agree.",
        "--",
        "-- Ids are explicit (TCH-<start year>-NNN, gap-free, in source order) rather",
        "-- than drawn from create_students_bulk(), precisely so they match the",
        "-- hardcoded copies. next_student_seq() reads students, so ids issued after",
        "-- this batch continue from the next number automatically.",
        "--",
        "-- Run ONCE, in a transaction (all-or-nothing). A clash with an existing id",
        "-- aborts the whole batch. Requires 0021 (admission columns).",
        "--",
        "-- The September 1st promotion for this session has ALREADY been run; this is",
        "-- the post-promotion JSS1 intake, so these students are not advanced by it.",
        "",
        "begin;",
        "",
        "insert into students (id, full_name, class_id, admitted_academic_year, admission_type) values",
    ]
    rows = [
        f"  ({sql_str(s['id'])}, {sql_str(s['full_name'])}, {sql_str(s['class_id'])}, {sql_str(year)}, {sql_str(atype)})"
        for s in students
    ]
    lines.append(",\n".join(rows) + ";")
    lines += ["", "commit;", ""]
    if not dry:
        path.write_text("\n".join(lines))
    return path


def write_pipeline_files(doc: dict, dry: bool) -> tuple[int, int]:
    sync = load_sync_module()
    seniority = sync.load_seniority_map()
    out_dir = PIPELINE / "students"
    created = skipped = 0
    for s in doc["students"]:
        f = out_dir / f"{s['id']}.json"
        if f.exists():
            skipped += 1
            continue
        skeleton = sync.build_skeleton(
            {"id": s["id"], "full_name": s["full_name"], "class_id": s["class_id"]}, seniority
        )
        if not dry:
            f.write_text(json.dumps(skeleton, indent=2, ensure_ascii=False))
        created += 1
    return created, skipped


def patch_portal(doc: dict, portal: Path, dry: bool) -> tuple[int, int]:
    target = portal / "src" / "lib" / "students.ts"
    text = target.read_text()
    present = set(re.findall(r'id:\s*"(TCH-\d{4}-\d+)"', text))
    new = [s for s in doc["students"] if s["id"] not in present]
    skipped = len(doc["students"]) - len(new)
    if not new:
        return 0, skipped
    block = "".join(
        f'\t{{ id: "{s["id"]}", full_name: "{s["full_name"]}", class_id: "{s["class_id"]}" }},\n'
        for s in new
    )
    end = text.rindex("];")
    text = text[:end] + block + text[end:]
    # The header's "NOT INCLUDED YET" note is now partly out of date.
    text = text.replace(
        "// NOT INCLUDED YET: the new JSS1 intake and students who joined other\n"
        "// classes since the roster was loaded -- their names were not available.\n"
        "// Add them to STUDENTS below (keep IDs exactly as issued by the school).",
        f"// {doc['academic_year']} JSS1 intake ({len(doc['students'])} students, TCH-"
        f"{doc['academic_year'][:4]}-NNN) added via tendercare-teacher's\n"
        "// scripts/intake/build_intake.py. NOT INCLUDED YET: students who joined\n"
        "// other classes since the roster was loaded -- add them below (keep IDs\n"
        "// exactly as issued by the school).",
    )
    if not dry:
        target.write_text(text)
    return len(new), skipped


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", type=Path)
    ap.add_argument("--seed-name", required=True, help="seed filename without .sql")
    ap.add_argument("--portal", type=Path, help="path to tendercare-portal checkout")
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    doc = json.loads(a.source.read_text())
    ids = [s["id"] for s in doc["students"]]
    if len(ids) != len(set(ids)):
        sys.exit("duplicate ids in source file")

    seed = write_seed(doc, a.seed_name, a.dry_run)
    c, sk = write_pipeline_files(doc, a.dry_run)
    print(f"seed:     {seed.relative_to(ROOT)}")
    print(f"pipeline: {c} created, {sk} already present")
    if a.portal:
        pc, psk = patch_portal(doc, a.portal, a.dry_run)
        print(f"portal:   {pc} added, {psk} already present")
    if a.dry_run:
        print("(dry run -- nothing written)")


if __name__ == "__main__":
    main()
