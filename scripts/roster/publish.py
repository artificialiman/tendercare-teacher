#!/usr/bin/env python3
"""
Hardcode the canonical roster (scripts/roster/students.json) into every place
that carries a copy, so no app has to ask a database:

  1. tendercare-teacher  src/lib/teacherData.ts        (generate_teacher_data.py)
  2. tendercare-teacher  report-pipeline skeletons     (one empty file per new active student)
  3. tendercare-portal   src/lib/students.ts           (directory: active students, regenerated in full)
  4. tendercare-portal   static/archive/class-of-YYYY/ (a frozen copy of each graduate's report)
  5. tendercare-web      src/lib/data/alumni.json      (archive: graduated students + results links)
  6. tendercare-admin    src/lib/classes.ts            (the class list the admin forms validate against)

Idempotent: running it twice changes nothing. Every step is a plain file write.

    python3 scripts/roster/publish.py --portal ../tendercare-portal --web ../tendercare-web \\
        --admin ../tendercare-admin [--dry-run]
"""
import argparse
import importlib.util
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

from common import ROOT, class_order, load_roster


def step_teacher(dry):
    if dry:
        print("teacher:  (dry run) would regenerate src/lib/teacherData.ts")
        return
    out = subprocess.run([sys.executable, str(ROOT / "scripts/generate_teacher_data.py")],
                         capture_output=True, text=True, check=True).stdout.splitlines()[0]
    print("teacher: ", out)


def step_pipeline(active, dry):
    spec = importlib.util.spec_from_file_location("build_intake", ROOT / "scripts/intake/build_intake.py")
    bi = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bi)
    # Only students admitted through this tooling get a skeleton. Legacy students
    # (null admission fields) were digitized -- or not -- by the report pipeline's
    # own sync; manufacturing hundreds of empty files for them would be noise.
    new = [s for s in active if s.get("admitted_academic_year")]
    created, skipped = bi.write_pipeline_files({"students": new}, dry)
    print(f"pipeline: {created} new skeletons, {skipped} already present")


def step_portal(portal, doc, order, dry):
    active = [s for s in doc["students"] if s["status"] == "active"]
    active.sort(key=lambda s: (order[s["class_id"]], s["id"]))
    target = portal / "src/lib/students.ts"
    text = target.read_text(encoding="utf-8")
    start = text.index("export const STUDENTS")
    head_end = text.index("[", start) + 1
    body = "".join('\t{ id: %s, full_name: %s, class_id: %s },\n' % (
        json.dumps(s["id"]), json.dumps(s["full_name"], ensure_ascii=False), json.dumps(s["class_id"]))
        for s in active)
    header = (
        "// ============================================================================\n"
        "// Student directory -- hardcoded on purpose.\n"
        "//\n"
        "// GENERATED by tendercare-teacher's scripts/roster/publish.py from its canonical\n"
        "// roster (scripts/roster/students.json). Do not edit by hand: change the roster\n"
        "// there (apply_changes.py) and re-publish. The portal never asks a database for\n"
        "// names, so it loads instantly and works on slow or dropped connections.\n"
        "//\n"
        f"// As of {doc['as_of']}, session {doc['session']}: {len(active)} active students.\n"
        "// Graduates are not listed here -- they live in tendercare-web's alumni archive.\n"
        "// ============================================================================\n\n"
        "export interface DirectoryEntry {\n\tid: string;\n\tfull_name: string;\n\tclass_id: string;\n}\n\n"
    )
    new = header + text[start:head_end].replace("export const STUDENTS", "export const STUDENTS") + "\n" + body + "];\n"
    old_ids = set(re.findall(r'id:\s*"(TCH-\d{4}-\d+)"', text))
    print(f"portal:   {len(active)} students ({len(set(s['id'] for s in active) - old_ids)} new, "
          f"{len(old_ids - set(s['id'] for s in active))} removed)")
    if not dry:
        target.write_text(new, encoding="utf-8")


def step_archive(portal, web, doc, order, dry):
    grads = [s for s in doc["students"] if s["status"] == "graduated"]
    years = sorted({s["graduated_on"][:4] for s in grads})
    copied = 0
    for y in years:
        d = portal / "static" / "archive" / f"class-of-{y}"
        for s in (g for g in grads if g["graduated_on"].startswith(y)):
            src, dst = portal / "static/reports" / f"{s['id']}.html", d / f"{s['id']}.html"
            if not dst.exists() and src.exists():
                copied += 1
                if not dry:
                    d.mkdir(parents=True, exist_ok=True)
                    shutil.copy(src, dst)
    print(f"archive:  {copied} report(s) frozen into the portal's class-of-YYYY folders")

    p = web / "src/lib/data/alumni.json"
    alumni = json.loads(p.read_text(encoding="utf-8"))
    classes = {c["id"]: c for c in __import__("common").seed_classes()}
    for y in years:
        people = sorted((s for s in grads if s["graduated_on"].startswith(y)),
                        key=lambda s: (classes[s["class_id"]]["arm"], s["full_name"].lower()))
        entry = alumni["classes"].setdefault(y, {"graduated_on": f"{y}-09-01",
                                                  "id_recycle_eligible_on": f"{int(y) + 1}-09-01", "alumni": []})
        entry["alumni"] = [{"name": s["full_name"], "arm": classes[s["class_id"]]["arm"],
                            "results_path": f"/archive/class-of-{y}/{s['id']}.html"} for s in people]
    alumni["generated_at"] = doc["as_of"]
    print("web:      " + ", ".join(f"class of {y}: {len(alumni['classes'][y]['alumni'])}" for y in years))
    if not dry:
        p.write_text(json.dumps(alumni, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def step_admin(admin, dry):
    from common import seed_classes
    rows = "".join("\t{ id: %s, label: %s, arm: %s, stage: %s, level: %d, sort_order: %d },\n" % (
        json.dumps(c["id"]), json.dumps(c["label"]), json.dumps(c["arm"]), json.dumps(c["stage"]),
        c["level"], c["sort_order"]) for c in seed_classes())
    text = (
        "// GENERATED by tendercare-teacher's scripts/roster/publish.py -- do not edit by hand.\n"
        "// The school's classes, hardcoded so the admin app never asks a database for them.\n\n"
        "export interface ClassEntry {\n\tid: string;\n\tlabel: string;\n\tarm: string;\n"
        "\tstage: 'JSS' | 'SS';\n\tlevel: number;\n\tsort_order: number;\n}\n\n"
        "export const CLASSES: readonly ClassEntry[] = [\n" + rows + "];\n")
    print(f"admin:    {len(seed_classes())} classes")
    if not dry:
        (admin / "src/lib/classes.ts").write_text(text, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--portal", type=Path)
    ap.add_argument("--web", type=Path)
    ap.add_argument("--admin", type=Path)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    doc, order = load_roster(), class_order()
    active = [s for s in doc["students"] if s["status"] == "active"]
    step_teacher(a.dry_run)
    step_pipeline(active, a.dry_run)
    if a.portal:
        step_portal(a.portal, doc, order, a.dry_run)
    if a.portal and a.web:
        step_archive(a.portal, a.web, doc, order, a.dry_run)
    if a.admin:
        step_admin(a.admin, a.dry_run)
    if a.dry_run:
        print("(dry run -- nothing written)")


if __name__ == "__main__":
    main()
